from __future__ import annotations

"""Build the two immutable Gate 0-A continuous-decode workload manifests.

The builder consumes exact local copies of the frozen WikiText Arrow file and
the public BurstGPT CSV.  It never samples routes or reads producer outputs.
"""

import argparse
import csv
from decimal import Decimal
import hashlib
import json
from pathlib import Path
from typing import Any, Mapping, Sequence


DATASET_REVISION = "b08601e04326c79dfdd32d625aee71d232d685c3"
DATASET_ARROW_SHA256 = "2b8a3efac7b468cbe6432edba5f55c21e435d93873acc6727431f08d5ed328ea"
DATASET_FINGERPRINT = "1d21d2114e992cd6"
ARRIVAL_REVISION = "d895a53bb7b8ec137d0d2fe203b335835a78c10a"
ARRIVAL_BLOB_OID = "f95dd2c84454b067fdd0973858c55ecfe31bdad7"
ARRIVAL_CSV_SHA256 = "46fc9480ef0b748ecb2b51d512ff08c196b031782cbe6f78e28044d768e86d5a"
ARRIVAL_TIME_SCALE_FACTOR = 1000
DEADLINE_BUDGET_US = 60_000_000
EXPECTED_REQUESTS = 128
MAX_PROMPT_TOKENS = 128
SEED = 20260725

MODEL_SPECS = (
    {
        "key": "olmoe",
        "id": "allenai/OLMoE-1B-7B-0924",
        "revision": "6d84c48581ece794365f2b8e9cfb043c68ade9c5",
        "dtype": "bfloat16",
    },
    {
        "key": "llmjp",
        "id": "llm-jp/optimal-sparsity-math-d512-E32-k16-920M-A520M",
        "revision": "1d5983076dfc67aee4a77ec06a27027f5bab6055",
        "dtype": "bfloat16",
    },
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset-arrow", required=True)
    parser.add_argument("--arrival-csv", required=True)
    parser.add_argument(
        "--output-dir",
        default=str(Path(__file__).resolve().parent / "configs" / "workloads"),
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare generated bytes with existing canonical files without writing",
    )
    return parser.parse_args()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def canonical_json_sha256(value: object) -> str:
    encoded = json.dumps(
        value, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def manifest_bytes(value: Mapping[str, Any]) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n"
    ).encode("utf-8")


def arrival_trace_sha256(requests: Sequence[Mapping[str, Any]]) -> str:
    payload = [
        {
            "sample_id": int(request["sample_id"]),
            "arrival_us": format(float(request["arrival_us"]), ".17g"),
            "deadline_us": format(float(request["deadline_us"]), ".17g"),
        }
        for request in sorted(
            requests,
            key=lambda item: (float(item["arrival_us"]), int(item["sample_id"])),
        )
    ]
    return canonical_json_sha256(payload)


def load_documents(path: Path) -> list[dict[str, Any]]:
    if sha256_file(path) != DATASET_ARROW_SHA256:
        raise ValueError("WikiText Arrow SHA-256 differs from the frozen source")
    try:
        from datasets import Dataset
    except ImportError as exc:
        raise RuntimeError("datasets is required to build workload manifests") from exc
    dataset = Dataset.from_file(str(path))
    if str(dataset._fingerprint) != DATASET_FINGERPRINT:  # noqa: SLF001
        raise ValueError("WikiText dataset fingerprint differs from the frozen source")
    documents: list[dict[str, Any]] = []
    for row_index, row in enumerate(dataset):
        prompt = str(row["text"])
        if not prompt.strip():
            continue
        prompt_sha256 = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
        documents.append(
            {
                "dataset_row_index": row_index,
                "document_id": (
                    f"wikitext-test-row-{row_index:06d}-{prompt_sha256[:16]}"
                ),
                "document_sha256": prompt_sha256,
                "prompt": prompt,
                "prompt_sha256": prompt_sha256,
            }
        )
        if len(documents) == EXPECTED_REQUESTS:
            break
    if len(documents) != EXPECTED_REQUESTS:
        raise ValueError("frozen selection did not produce exactly 128 documents")
    return documents


def load_arrivals(path: Path) -> tuple[list[dict[str, Any]], Decimal]:
    if sha256_file(path) != ARRIVAL_CSV_SHA256:
        raise ValueError("BurstGPT CSV SHA-256 differs from the frozen source")
    selected: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        expected_fields = [
            "Timestamp",
            "Model",
            "Request tokens",
            "Response tokens",
            "Total tokens",
            "Log Type",
        ]
        if reader.fieldnames != expected_fields:
            raise ValueError("BurstGPT CSV schema differs from the frozen source")
        for source_data_index, row in enumerate(reader):
            if source_data_index >= EXPECTED_REQUESTS:
                break
            selected.append(
                {
                    "source_csv_row": source_data_index + 2,
                    "source_timestamp_s": Decimal(str(row["Timestamp"])),
                }
            )
    if len(selected) != EXPECTED_REQUESTS:
        raise ValueError("BurstGPT selection did not produce exactly 128 arrivals")
    origin = selected[0]["source_timestamp_s"]
    for item in selected:
        delta_seconds = item["source_timestamp_s"] - origin
        scaled_us = delta_seconds * Decimal(1_000_000) / Decimal(
            ARRIVAL_TIME_SCALE_FACTOR
        )
        if scaled_us != scaled_us.to_integral_value():
            raise ValueError("scaled BurstGPT timestamp is not an integer microsecond")
        item["arrival_us"] = int(scaled_us)
        item["deadline_us"] = int(scaled_us) + DEADLINE_BUDGET_US
        item["source_timestamp_s"] = str(item["source_timestamp_s"])
    return selected, origin


def tokenizer_contract(model_spec: Mapping[str, str]) -> tuple[object, dict[str, Any]]:
    try:
        from huggingface_hub import snapshot_download
        from transformers import AutoTokenizer
    except ImportError as exc:
        raise RuntimeError(
            "huggingface_hub and transformers are required to build manifests"
        ) from exc
    revision = str(model_spec["revision"])
    snapshot = Path(
        snapshot_download(
            repo_id=str(model_spec["id"]),
            revision=revision,
            local_files_only=True,
        )
    )
    files: dict[str, str] = {}
    for name in ("special_tokens_map.json", "tokenizer.json", "tokenizer_config.json"):
        source = snapshot / name
        if not source.is_file():
            raise ValueError(f"tokenizer snapshot is missing {name}")
        files[name] = sha256_file(source)
    tokenizer = AutoTokenizer.from_pretrained(
        str(model_spec["id"]), revision=revision, local_files_only=True
    )
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    contract = {
        "revision": revision,
        "class": type(tokenizer).__name__,
        "vocab_size": int(tokenizer.vocab_size),
        "length": int(len(tokenizer)),
        "eos_token_id": tokenizer.eos_token_id,
        "pad_token_id": tokenizer.pad_token_id,
        "truncation_side": str(tokenizer.truncation_side),
        "files": files,
        "files_sha256": canonical_json_sha256(files),
    }
    return tokenizer, contract


def build_manifest(
    model_spec: Mapping[str, str],
    documents: Sequence[Mapping[str, Any]],
    arrivals: Sequence[Mapping[str, Any]],
    arrival_origin: Decimal,
) -> dict[str, Any]:
    tokenizer, tokenizer_spec = tokenizer_contract(model_spec)
    requests: list[dict[str, Any]] = []
    for sample_id, (document, arrival) in enumerate(zip(documents, arrivals)):
        encoded = tokenizer(
            str(document["prompt"]),
            add_special_tokens=True,
            truncation=True,
            max_length=MAX_PROMPT_TOKENS,
        )
        token_ids = [int(value) for value in encoded["input_ids"]]
        request = {
            "request_id": f"gate0-{sample_id:03d}",
            "sample_id": sample_id,
            **dict(document),
            "prompt_token_count": len(token_ids),
            "prompt_token_ids_sha256": canonical_json_sha256(token_ids),
            **dict(arrival),
        }
        requests.append(request)
    trace_hash = arrival_trace_sha256(requests)
    return {
        "schema": "bcrd-continuous-workload-v1",
        "run_class": "formal",
        "seed": SEED,
        "expected_requests": EXPECTED_REQUESTS,
        "max_prompt_tokens": MAX_PROMPT_TOKENS,
        "model": {
            **dict(model_spec),
            "tokenizer_revision": str(model_spec["revision"]),
        },
        "tokenizer": tokenizer_spec,
        "tokenization": {
            "add_special_tokens": True,
            "truncation": True,
            "max_length": MAX_PROMPT_TOKENS,
            "padding": False,
        },
        "dataset": {
            "id": "wikitext",
            "config": "wikitext-103-raw-v1",
            "split": "test",
            "revision": DATASET_REVISION,
            "arrow_sha256": DATASET_ARROW_SHA256,
            "fingerprint": DATASET_FINGERPRINT,
            "text_field": "text",
            "selection_rule": "first_128_nonempty_rows_in_dataset_index_order",
            "prompt_policy": "raw_text_verbatim_before_model_tokenizer_truncation",
        },
        "generation": {
            "mode": "greedy",
            "do_sample": False,
            "max_decode_steps": 16,
        },
        "scheduler": {
            "max_batch_size": 8,
            "arrival_trace_sha256": trace_hash,
            "arrival_source": {
                "kind": "real_world_llm_serving_trace",
                "name": "BurstGPT_1",
                "repository": "https://github.com/HPMLL/BurstGPT",
                "revision": ARRIVAL_REVISION,
                "path": "data/BurstGPT_1.csv",
                "git_blob_oid": ARRIVAL_BLOB_OID,
                "sha256": ARRIVAL_CSV_SHA256,
                "license": "CC-BY-4.0",
                "selection_rule": "first_128_data_rows_after_header",
                "source_csv_rows": [2, 129],
                "timestamp_field": "Timestamp",
                "timestamp_unit": "seconds",
                "source_time_origin_s": str(arrival_origin),
                "time_scale_factor": ARRIVAL_TIME_SCALE_FACTOR,
                "scaled_time_unit": "microseconds",
                "deadline_policy": "scaled_arrival_plus_60000000_us",
            },
        },
        "software": {"execution_policy": "clean_committed_head"},
        "serial_audit_request_ids": [
            f"gate0-{sample_id:03d}" for sample_id in range(EXPECTED_REQUESTS)
        ],
        "requests": requests,
    }


def main() -> None:
    args = parse_args()
    dataset_arrow = Path(args.dataset_arrow).resolve()
    arrival_csv = Path(args.arrival_csv).resolve()
    output_dir = Path(args.output_dir).resolve()
    documents = load_documents(dataset_arrow)
    arrivals, origin = load_arrivals(arrival_csv)
    generated = {
        str(spec["key"]): manifest_bytes(
            build_manifest(spec, documents, arrivals, origin)
        )
        for spec in MODEL_SPECS
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    for model_key, payload in generated.items():
        path = output_dir / f"{model_key}.formal.json"
        if args.check:
            if not path.is_file() or path.read_bytes() != payload:
                raise SystemExit(f"manifest drift: {path}")
        else:
            if path.exists():
                raise SystemExit(f"refusing to overwrite existing manifest: {path}")
            path.write_bytes(payload)
        print(f"{sha256_file(path)}  {path}")


if __name__ == "__main__":
    main()
