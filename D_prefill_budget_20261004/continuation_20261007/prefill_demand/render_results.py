#!/usr/bin/env python3
"""Render two small LaTeX includes from completed, unchanged analysis JSON."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CELLS = ['00_fixed1024', '01_prefill_demand', '02_prefill_demand', '03_fixed1024']
PAIRS = [('00_fixed1024', '01_prefill_demand'), ('03_fixed1024', '02_prefill_demand')]


def panel(title, ylabel, series, precision):
    lines = [r'\begin{minipage}[t]{0.49\linewidth}', r'\centering', r'\begin{tikzpicture}',
        r'\begin{axis}[width=\linewidth,height=58mm,',
        r'font=\small,ybar=1.5pt,bar width=7pt,',
        r'symbolic x coords={Pair 1,Pair 2},xtick=data,',
        r'enlarge x limits=0.35,enlarge y limits=0.25,',
        r'ymajorgrids=true,grid style={gray!20},axis line style={gray!60},',
        r'tick style={gray!60},scaled y ticks=false,',
        'title={'+title+'},ylabel={'+ylabel+'},',
        r'nodes near coords,point meta=y,',
        r'every node near coord/.append style={font=\tiny,/pgf/number format/fixed,',
        '/pgf/number format/precision='+str(precision)+'},',
        r'legend style={at={(0.5,-0.2)},anchor=north,draw=none,font=\scriptsize},',
        r'legend columns=3]']
    for label, color, values in series:
        coordinates = ' '.join(f'(Pair {i+1},{value:.9f})' for i, value in enumerate(values))
        lines += [f'\\addplot+[fill={color},draw={color}] coordinates {{{coordinates}}};',
                  '\\addlegendentry{'+label+'}']
    return '\n'.join(lines+[r'\end{axis}', r'\end{tikzpicture}', r'\end{minipage}'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('run_directory', nargs='?', type=Path, default=ROOT/'demand53005_02')
    args = parser.parse_args(); run = args.run_directory
    source_bytes = (run/'demand_results.json').read_bytes()
    source = json.loads(source_bytes)
    decomposition = json.loads((run/'service_decomposition.json').read_text())
    assert source['status'] == 'COMPLETE_EXPLORATORY'
    assert decomposition['status'] == 'COMPLETE_SUPPLEMENTAL_ANALYSIS'
    assert decomposition['source_results_sha256'] == hashlib.sha256(source_bytes).hexdigest(), 'Sources disagree'
    assert len(source['pairs']) == len(decomposition['pairs']) == 2
    assert [(p['fixed_cell'], p['component_cell']) for p in source['pairs']] == PAIRS
    assert [(p['fixed_cell'], p['demand_cell']) for p in decomposition['pairs']] == PAIRS
    rows = {r['cell']: r for r in source['runs'] if r['cell'] in CELLS}
    assert set(rows) == set(CELLS)
    assert all(r['valid'] and r['summary']['request_count'] == r['summary']['finished_count'] == 256 for r in rows.values())
    assert all(p['status'] == 'DESCRIBED' and p['all_requests']['request_count'] == 256 for p in decomposition['pairs'])

    table = ['% Generated by prefill_demand/render_results.py; no floating wrapper.',
        '% Requires booktabs. Width170mm; max-gap column is milliseconds.',
        r'\begingroup\small\setlength{\tabcolsep}{4pt}',
        r'\begin{tabular*}{170mm}{@{\extracolsep{\fill}}lrrrrrr@{}}', r'\toprule',
        r'Cell / policy & Qualified & $U$ (req/s) & Elapsed (s) & TTFT p95 (s) & Flow p95 (s) & Gap p95 (ms) \\',
        r'\midrule']
    for cell in CELLS:
        s = rows[cell]['summary']; number, policy = cell.split('_', 1)
        label = 'Fixed 1024' if policy == 'fixed1024' else 'Demand'
        table.append(f'{number} / {label} & {s["joint_slo_qualified_requests"]}/{s["request_count"]} & '
            f'{s["joint_slo_requests_per_s"]:.4f} & {s["elapsed_s"]:.3f} & '
            f'{s["ttft_p95_s"]:.3f} & {s["completion_flow_p95_s"]:.3f} & '
            f'{1000*s["request_max_gap_p95_s"]:.3f} '+r'\\')
    table += [r'\bottomrule', r'\end{tabular*}\par', r'\endgroup', '']

    pairs = decomposition['pairs']
    mean = lambda key: [p['all_requests']['metrics'][key]['demand_minus_fixed']['mean'] for p in pairs]
    series = [('TTFT', 'blue!65', mean('ttft_s')),
              ('Generation', 'orange!80!black', mean('generation_span_s')),
              ('Flow', 'black!65', mean('flow_s'))]
    # The completed dataset has zero finish remainder; retain it if rendering a
    # different compatible dataset where it is nonzero, rather than hiding it.
    remainder = mean('finish_remainder_s')
    if any(v != 0 for v in remainder): series.insert(2, ('Finish remainder', 'green!50!black', remainder))
    added = [len(p['qualified_added_ids']) for p in pairs]
    lost = [-len(p['qualified_lost_ids']) for p in pairs]
    net = [p['U_decomposition']['demand_N']-p['U_decomposition']['fixed_N'] for p in pairs]
    assert all(a+l == n for a, l, n in zip(added, lost, net)), 'Qualification sources disagree'
    figure = '\n'.join([
        '% Generated from service_decomposition.json; requires tikz and pgfplots.',
        '% No figure float. Pair1=F00/D01; Pair2=F03/D02. Changes are Demand minus Fixed.',
        '% TTFT is the first-output interval, not isolated queue time. Full elapsed defines U.',
        '% Mean finish-remainder changes (s): '+', '.join(f'{v:.9f}' for v in remainder),
        panel('(a) Mean service-time change', 'Demand minus Fixed (s)', series, 2),
        r'\hfill%',
        panel('(b) Joint-SLO qualifications', 'Requests',
              [('Added', 'blue!65', added), ('Lost', 'orange!80!black', lost), ('Net', 'black!65', net)], 0), ''])
    output = run/'presentation'; output.mkdir(exist_ok=True)
    (output/'service_table.tex').write_text('\n'.join(table))
    (output/'service_figure.tex').write_text(figure)
    print(f'Generated {output}/service_table.tex and service_figure.tex; analysis JSON unchanged.')


if __name__ == '__main__': main()
